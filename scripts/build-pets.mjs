/*
 * build-pets.mjs — writes assets/js/pets.js: which properties welcome pets, and the
 * policy in the source's own words. Nothing is inferred from names or brands.
 *
 * Sources
 *   Hotels and resorts: scripts/pet-policies.json (from scripts/fetch-pet-policies.mjs,
 *     the FAQ on each property's WhataHotel page).
 *   Mandarin Oriental Exceptional Homes: assets/js/mo-homes.js, a home whose
 *     "This Home is Suitable For" list on Mandarin Oriental includes "Pets".
 *   WhataHotel's Pet-Friendly Luxury Hotels collection (scripts/pet-collection.json, from
 *     scripts/fetch-pet-collection.mjs): a property listed there whose own page has no pet
 *     answer is marked pet-friendly with that listing as the source.
 *
 *   Hotels' official websites: scripts/pet-policies-official.json, for properties whose
 *     WhataHotel page has no pet answer (copied word for word, with the page URL).
 *
 * Output: window.WAH_PETS = { "<id>": { ok: 1|0, text: "<policy>", src: "whatahotel"|"mo"|"official"|"collection" } }
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import vm from "node:vm";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const load = (file) => { const sb = { window: {} }; vm.runInNewContext(readFileSync(join(root, "assets", "js", file), "utf8"), sb); return sb.window; };

// Only the pet part of an FAQ answer: sentences that mention pets, plus a directly
// following sentence about fees, weight or rules ("A non-refundable cleaning fee …").
const PET_WORD = /\b(pets?|pet-friendly|dogs?|cats?|four-legged|furry|companions?)\b/i;
const PET_DETAIL = /\b(fee|fees|charge|charged|weigh|weight|pounds?|lbs?|kg|kilograms?|per stay|per night|deposit|leash|carrier|vaccinat|room types|advance|certificate|identification|accommodations?)\b/i;
function petSentences(answer) {
  // Sentence ends: . ! ? followed by a space and a capital — never "$250.00", "St. Regis".
  const parts = [];
  answer.split(/(?<=[.!?])\s+(?=[A-Z"“])/).forEach((t) => {
    if (parts.length && /\b(St|Dr|Mr|Mrs|Ms|No|approx|Approx)\.$/.test(parts[parts.length - 1])) parts[parts.length - 1] += " " + t;
    else parts.push(t);
  });
  const keep = []; let prev = false;
  for (const raw of parts) {
    const t = raw.trim();
    if (PET_WORD.test(t) || (prev && PET_DETAIL.test(t))) { keep.push(t); prev = true; } else prev = false;
  }
  return keep.length ? keep.join(" ") : answer;
}

const ids = new Set(load("data.js").WAH_PROPERTIES.map((p) => String(p.id)));
const policies = JSON.parse(readFileSync(join(__dirname, "pet-policies.json"), "utf8"));
const out = {};
for (const [id, v] of Object.entries(policies)) {
  if (!ids.has(id) || (v.status !== "yes" && v.status !== "no")) continue;   // only properties on the page, clear answers only
  out[id] = { ok: v.status === "yes" ? 1 : 0, text: petSentences(v.answer), src: "whatahotel" };
}

const mo = load("mo-homes.js");
const homes = (mo.WAH_MO_HOMES || mo.WAH_MO_DATA || {}).homes || mo.WAH_MO_HOMES || [];
for (const h of homes) {
  const blocks = h.details || [];
  for (let i = 0; i < blocks.length - 1; i++) {
    if (blocks[i].type === "heading" && /suitable for/i.test(blocks[i].text || "") && /\bpets?\b/i.test(blocks[i + 1].text || "")) {
      out[h.id] = { ok: 1, text: "Suitable for: " + blocks[i + 1].text + " (Mandarin Oriental).", src: "mo" };
    }
  }
}

// The hotel's official website, where its WhataHotel page says nothing about pets.
try {
  const off = JSON.parse(readFileSync(join(__dirname, "pet-policies-official.json"), "utf8"));
  for (const [id, v] of Object.entries(off)) if (/^\d+$/.test(id) && ids.has(id) && !out[id]) out[id] = { ok: 1, text: v.text, src: "official" };
} catch (e) { /* optional file */ }

// Listed in WhataHotel's pet-friendly collection but no pet FAQ on its own page.
try {
  const coll = JSON.parse(readFileSync(join(__dirname, "pet-collection.json"), "utf8"));
  for (const h of coll.hotels) {
    const id = String(h.id);
    if (ids.has(id) && !out[id]) out[id] = { ok: 1, text: "Listed in WhataHotel's Pet-Friendly Luxury Hotels collection. Pet rules are set by the hotel and can change; an advisor confirms the fee, weight limit, number of pets and room types before you book.", src: "collection" };
  }
} catch (e) { console.warn("  (no scripts/pet-collection.json — run npm run pets:collection)"); }

const yes = Object.values(out).filter((v) => v.ok).length;
writeFileSync(join(root, "assets", "js", "pets.js"),
  "/*\n * Pet policies, word for word from each property's WhataHotel page (FAQ) or, for the\n" +
  " * Mandarin Oriental Exceptional Homes, their \"This Home is Suitable For\" list.\n" +
  " * AUTO-GENERATED by scripts/build-pets.mjs — do not edit.\n */\n" +
  "window.WAH_PETS = " + JSON.stringify(out, null, 1) + ";\n");
console.log(`Pets: ${yes} pet-friendly (${Object.values(out).filter((v) => v.src === "mo").length} of them Exceptional Homes), ${Object.keys(out).length - yes} not pet-friendly`);
